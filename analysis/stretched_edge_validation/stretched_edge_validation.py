"""Stretched-edge distortion metric for the vertex-based straightening method.

Edges longer than 8x each dataset's own median edge length are flagged and
counted, as a percentage of all edges and per metre of colon length. The
median is computed from the straightened mesh's own edges. Edges are
per-face, non-deduplicated (3 per face, n_edges = 3 * n_faces).

Reads the already-generated colon_straightened_*.stl files rather than
re-running straighten_mesh.
"""
import json
import os
import sys
import numpy as np
from stl import mesh as stl_mesh

_ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..")
sys.path.insert(0, _ROOT)
sys.path.insert(0, os.path.join(_ROOT, "analysis", "validate_batch"))
import colon_core as cf
from validate_batch import DATASETS

OUT_DIR = os.path.dirname(os.path.abspath(__file__))


def per_face_edge_lengths(vectors):
    """vectors: (n_faces, 3, 3) array of per-face vertex positions.
    Returns a flat (n_faces*3,) array of the 3 edge lengths per face."""
    v0, v1, v2 = vectors[:, 0], vectors[:, 1], vectors[:, 2]
    e01 = np.linalg.norm(v1 - v0, axis=1)
    e12 = np.linalg.norm(v2 - v1, axis=1)
    e20 = np.linalg.norm(v0 - v2, axis=1)
    return np.concatenate([e01, e12, e20])


def validate_one(entry):
    name = entry["name"]
    print(f"\n{'='*70}\nStretched-edge check: {name}\n{'='*70}")
    cf.MESH_UPSAMPLE = 1

    # original mesh: used to confirm the face count is preserved by straightening
    verts, faces = cf.load_nifti_mesh(entry["nifti"], label_value=entry["label"])

    # straightened mesh, generated by generate_straightened_mesh.py
    stl_path = f"{entry['nifti'].rsplit('/', 1)[0]}/colon_straightened_{name}.stl"
    straightened = stl_mesh.Mesh.from_file(stl_path)
    if straightened.vectors.shape[0] != faces.shape[0]:
        raise ValueError(
            f"{name}: face count mismatch between original mesh ({faces.shape[0]}) "
            f"and straightened STL ({straightened.vectors.shape[0]}) -- "
            "straighten_mesh is supposed to preserve topology, this should never happen"
        )
    straight_edges = per_face_edge_lengths(straightened.vectors)
    median_edge_mm = float(np.median(straight_edges))

    threshold = 8.0 * median_edge_mm
    n_stretched = int((straight_edges > threshold).sum())
    n_edges = int(len(straight_edges))
    pct_stretched = round(100.0 * n_stretched / n_edges, 4)

    cl_pts = cf.load_centerline_slicer(entry["centerline"])
    cl_pts = cf.resample_centerline(cl_pts, step_mm=cf.ARC_STEP_MM)
    arc, *_ = cf.build_centerline_frame(cl_pts)
    arc_len_mm = float(arc[-1])
    stretched_per_m = round(n_stretched / (arc_len_mm / 1000.0), 2)

    print(f"  median original edge: {median_edge_mm:.3f}mm  threshold (8x): {threshold:.3f}mm")
    print(f"  n_edges={n_edges}  n_stretched={n_stretched}  pct_stretched={pct_stretched}%")
    print(f"  arc_len={arc_len_mm:.1f}mm  stretched_per_m={stretched_per_m}")

    return {
        "name": name,
        "median_edge_mm": round(median_edge_mm, 3),
        "n_edges": n_edges,
        "n_stretched": n_stretched,
        "pct_stretched": pct_stretched,
        "stretched_per_m": stretched_per_m,
        "arc_len_mm": round(arc_len_mm, 1),
    }


if __name__ == "__main__":
    results = []
    for entry in DATASETS:
        try:
            results.append(validate_one(entry))
        except Exception as e:
            print(f"FAILED on {entry['name']}: {e}")

    with open(os.path.join(OUT_DIR, "stretched_edge_results.json"), "w") as f:
        json.dump(results, f, indent=2)

    print(f"\n{'='*70}\nSUMMARY\n{'='*70}")
    for r in results:
        print(f"{r['name']:8s} median={r['median_edge_mm']:.3f}mm  "
              f"pct_stretched={r['pct_stretched']:.3f}%  stretched_per_m={r['stretched_per_m']}")
    print("\nSaved stretched_edge_results.json")
